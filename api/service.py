"""Model inference service, caching, and feature alignment."""

from __future__ import annotations

import json
import logging
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

# Ensure project root is on sys.path
PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import joblib
import numpy as np
import pandas as pd
from sklearn.pipeline import Pipeline

from api.schemas import (
    ApplicantFeatures,
    BatchPredictionResponse,
    SinglePredictionResponse,
)
from src.data.loader import ALL_RAW_FEATURES
from src.models.explainability import explain_single_applicant

logger = logging.getLogger(__name__)

DISCLAIMER_TEXT = (
    "EXPERIMENTAL PROTOTYPE: This prediction is generated by a decision-support model "
    "for risk evaluation only. It is not an automated adverse credit decision. "
    "Final credit approvals require compliance with ECOA, FCRA, and human underwriting."
)


class CreditRiskService:
    """Manages loaded pipeline, metadata, and inference execution."""

    def __init__(self, model_path: Optional[Path] = None, metadata_path: Optional[Path] = None):
        project_root = Path(__file__).resolve().parents[1]
        self.model_path = model_path or (project_root / "artifacts" / "models" / "best_model.joblib")
        self.metadata_path = metadata_path or (project_root / "artifacts" / "models" / "model_metadata.json")

        self.pipeline: Optional[Pipeline] = None
        self.metadata: Dict[str, Any] = {}
        self.default_threshold: float = 0.38
        self.model_name: str = "Unknown"
        self.model_version: str = "1.0.0"

        self._load_artifacts()

    def _load_artifacts(self) -> None:
        """Load serialized pipeline and metadata into memory."""
        if self.metadata_path.exists():
            try:
                with open(self.metadata_path, "r") as f:
                    self.metadata = json.load(f)
                self.default_threshold = float(self.metadata.get("selected_decision_threshold", 0.38))
                self.model_name = self.metadata.get("champion_model_name", "RandomForest")
                logger.info(f"Loaded model metadata: {self.model_name}, Threshold: {self.default_threshold}")
            except Exception as e:
                logger.error(f"Failed to load model metadata: {e}")

        if self.model_path.exists():
            try:
                self.pipeline = joblib.load(self.model_path)
                logger.info(f"Loaded trained pipeline from {self.model_path}")
            except Exception as e:
                logger.error(f"Failed to load model pipeline: {e}")
        else:
            logger.warning(f"Model artifact not found at {self.model_path}. Run training pipeline first.")

    @property
    def is_ready(self) -> bool:
        """Check if pipeline is loaded and ready for inference."""
        return self.pipeline is not None

    def _applicant_to_dataframe(self, applicant: ApplicantFeatures) -> pd.DataFrame:
        """Convert Pydantic applicant model to DataFrame with strictly aligned columns."""
        data = applicant.model_dump()
        row = {col: data[col] for col in ALL_RAW_FEATURES}
        return pd.DataFrame([row])

    def _batch_to_dataframe(self, applicants: List[ApplicantFeatures]) -> pd.DataFrame:
        """Convert list of applicant models to DataFrame with strictly aligned columns."""
        rows = []
        for app in applicants:
            data = app.model_dump()
            rows.append({col: data[col] for col in ALL_RAW_FEATURES})
        return pd.DataFrame(rows)

    def predict_single(
        self, applicant: ApplicantFeatures, custom_threshold: Optional[float] = None
    ) -> SinglePredictionResponse:
        """Generate prediction and explanations for a single applicant."""
        if not self.is_ready:
            raise RuntimeError("Model pipeline is not loaded. Train the model first.")

        threshold = custom_threshold if custom_threshold is not None else self.default_threshold
        df = self._applicant_to_dataframe(applicant)

        # Predict probability of default (class 1)
        proba = float(self.pipeline.predict_proba(df)[0, 1])
        predicted_class = int(proba >= threshold)

        # Risk categorization
        if proba < 0.20:
            risk_category = "Low"
            recommendation = "Low default risk. Eligible for standard credit terms."
        elif proba < threshold:
            risk_category = "Medium"
            recommendation = "Moderate risk. Under threshold; eligible with monitoring or conservative limit."
        else:
            risk_category = "High"
            recommendation = (
                f"High default risk (probability {proba:.1%} exceeds threshold {threshold:.1%}). "
                "Secondary underwriter review or collateral required."
            )

        # Local feature attribution explanations
        feature_names = self.metadata.get("preprocessed_feature_names", [])
        explanation = explain_single_applicant(self.pipeline, df, feature_names, top_k=4)

        return SinglePredictionResponse(
            default_probability=round(proba, 4),
            predicted_class=predicted_class,
            risk_category=risk_category,
            threshold_applied=round(threshold, 3),
            recommendation=recommendation,
            model_name=self.model_name,
            model_version=self.model_version,
            key_risk_drivers=explanation["risk_increasing_factors"],
            disclaimer=DISCLAIMER_TEXT,
        )

    def predict_batch(
        self, applicants: List[ApplicantFeatures], custom_threshold: Optional[float] = None
    ) -> BatchPredictionResponse:
        """Generate predictions for a cohort of applicants."""
        if not self.is_ready:
            raise RuntimeError("Model pipeline is not loaded.")

        threshold = custom_threshold if custom_threshold is not None else self.default_threshold
        df = self._batch_to_dataframe(applicants)

        probas = self.pipeline.predict_proba(df)[:, 1]
        preds = (probas >= threshold).astype(int)

        feature_names = self.metadata.get("preprocessed_feature_names", [])
        single_responses: List[SinglePredictionResponse] = []

        for idx, (p, c) in enumerate(zip(probas, preds)):
            p = float(p)
            c = int(c)
            if p < 0.20:
                cat = "Low"
                rec = "Eligible for standard terms."
            elif p < threshold:
                cat = "Medium"
                rec = "Eligible with conservative limit."
            else:
                cat = "High"
                rec = "High risk. Underwriter review required."

            single_df = df.iloc[[idx]]
            exp = explain_single_applicant(self.pipeline, single_df, feature_names, top_k=3)

            single_responses.append(
                SinglePredictionResponse(
                    default_probability=round(p, 4),
                    predicted_class=c,
                    risk_category=cat,
                    threshold_applied=round(threshold, 3),
                    recommendation=rec,
                    model_name=self.model_name,
                    model_version=self.model_version,
                    key_risk_drivers=exp["risk_increasing_factors"],
                    disclaimer=DISCLAIMER_TEXT,
                )
            )

        default_count = int(np.sum(preds))
        total_count = len(applicants)

        return BatchPredictionResponse(
            total_records=total_count,
            default_count=default_count,
            non_default_count=total_count - default_count,
            predicted_default_rate=round(default_count / total_count, 4) if total_count > 0 else 0.0,
            threshold_applied=round(threshold, 3),
            predictions=single_responses,
            disclaimer=DISCLAIMER_TEXT,
        )


# Singleton instance
credit_service = CreditRiskService()
